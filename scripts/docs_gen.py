def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower().replace("_", "-")


def parse_cli(root: Path = ROOT) -> list[dict]:
    text = (root / "tooling/content-builder/src/main.rs").read_text(encoding="utf-8")
    body = text.split("enum Commands {", 1)[1]
    commands: list[dict] = []
    docs: list[str] = []
    attr = ""
    current: dict | None = None
    depth = 1
    for raw in body.split("\n"):
        line = raw.strip()
        if depth == 1:
            if line.startswith("///"):
                docs.append(line[3:].strip())
            elif m := re.match(r"(\w+)\s*(\{|,)", line):
                current = {"name": kebab(m.group(1)), "doc": " ".join(docs), "args": []}
                commands.append(current)
                docs = []
        elif depth == 2 and current is not None:
            if line.startswith("///"):
                docs.append(line[3:].strip())
            elif line.startswith("#[arg("):
                attr = line
            elif m := re.match(r"(\w+):\s*(.+),$", line):
                field, ty = m.group(1), m.group(2)
                env = re.search(r'env\s*=\s*"([^"]+)"', attr)
                default = re.search(r"default_value\s*=\s*([^,)]+)", attr)
                default_text = default.group(1).strip().strip('"') if default else ""
                if default_text == "DEFAULT_API_BASE":
                    default_text = "https://api.curated.games"
                current["args"].append(
                    {
                        "flag": f"--{field.replace('_', '-')}",
                        "type": ty,
                        "env": env.group(1) if env else "",
                        "default": default_text,
                        "required": not ty.startswith("Option<") and not default,
                        "doc": " ".join(docs),
                    }
                )
                docs = []
                attr = ""
        depth += raw.count("{") - raw.count("}")
        if depth == 0:
            break
    return commands


def parse_script_fields(root: Path = ROOT) -> list[tuple[str, list[tuple[str, str, str]]]]:
    text = (root / "tooling/content-builder/src/config.rs").read_text(encoding="utf-8")
    out = []
    for struct, label in (("BuildScript", "Top level"), ("DepotMapping", "[[depots]] entries")):
        body = text.split(f"pub struct {struct} {{", 1)[1].split("\n}", 1)[0]
        fields: list[tuple[str, str, str]] = []
        doc = ""
        for raw in body.split("\n"):
            line = raw.strip()
            if line.startswith("///"):
                doc = (doc + " " + line[3:].strip()).strip()
            elif m := re.match(r"pub (\w+):\s*(.+),$", line):
                fields.append((m.group(1), m.group(2), doc))
                doc = ""
        out.append((label, fields))
    return out


def cli_reference_page() -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Content Builder CLI",
        "",
        "Every command and flag of `curated-content-builder`, parsed from "
        f"[`tooling/content-builder/src/main.rs`]({REPO_URL}/blob/main/tooling/content-builder/src/main.rs) "
        "at build time. For a walkthrough, see [Content Builder](/guide/content-builder).",
        "",
    ]
    for cmd in parse_cli():
        lines += [f"## {cmd['name']}", "", md_text(cmd["doc"]), "", "```bat", f"curated-content-builder {cmd['name']}" + "".join(
            f" {a['flag']} <{a['flag'][2:]}>" for a in cmd["args"] if a["required"]
        ), "```", ""]
        if cmd["args"]:
            lines += ["| Flag | Environment variable | Default | Description |", "| --- | --- | --- | --- |"]
            for a in cmd["args"]:
                req = " (required)" if a["required"] else ""
                lines.append(
                    f"| `{a['flag']}`{req} | {('`' + a['env'] + '`') if a['env'] else ''} | "
                    f"{('`' + a['default'] + '`') if a['default'] else ''} | {cell(a['doc'])} |"
                )
            lines.append("")
    lines += [
        "## Build script fields",
        "",
        "`upload --script <file>.toml` reads these fields. Paths are relative to the script file. "
        f"Parsed from [`src/config.rs`]({REPO_URL}/blob/main/tooling/content-builder/src/config.rs).",
        "",
    ]
    for label, fields in parse_script_fields():
        lines += [f"### {md_text(label)}", "", "| Field | Type | Description |", "| --- | --- | --- |"]
        for name, ty, doc in fields:
            lines.append(f"| `{name}` | `{ty}` | {cell(doc)} |")
        lines.append("")
    return "\n".join(lines)


