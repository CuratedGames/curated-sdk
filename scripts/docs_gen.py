def reference_page(binding: str, manifest: dict) -> str:
    info = public_api.BINDINGS[binding]
    descriptions: dict[str, str] = manifest["bindings"][binding]
    members = public_api.extract(binding)
    lang = LANG[binding]
    lines = [
        GENERATED_NOTE,
        "",
        f"# {info['title']}",
        "",
        "Every public member of this binding, generated from "
        f"[`contracts/public-api.v1.json`]({REPO_URL}/blob/main/contracts/public-api.v1.json) and the "
        "source files below. CI fails when the two disagree, so this page always matches the code.",
        "",
        "Sources: " + ", ".join(f"[`{s}`]({REPO_URL}/blob/main/{s})" for s in public_api.sources(binding)),
        "",
    ]
    groups: dict[str, list[public_api.Member]] = {}
    for m in members:
        groups.setdefault(m.group, []).append(m)
    for group, items in groups.items():
        head = next((m for m in items if m.name == group), None)
        lines += [f"## {group}", ""]
        if head:
            label = KIND_LABEL.get(head.kind, head.kind)
            lines += [f"<Badge type=\"info\" text=\"{label}\" />", ""]
            if descriptions.get(head.name):
                lines += [md_text(descriptions[head.name]), ""]
            if head.signatures:
                lines += [f"```{lang}", *head.signatures, "```", ""]
        rows = [m for m in items if m is not head and m.kind in TABLE_KINDS]
        if rows:
            lines += ["| Member | Kind | Description |", "| --- | --- | --- |"]
            for m in rows:
                short = m.name[len(group) + 1 :] if m.name.startswith(group) else m.name
                sig = f"<br>`{m.signatures[0]}`" if m.signatures and m.kind not in ("plugin-parameter", "plugin-command") else ""
                if m.kind in ("plugin-parameter", "plugin-command") and m.signatures:
                    sig = f"<br>Shown as **{cell(m.signatures[0])}**"
                lines.append(f"| `{short}`{sig} | {m.kind} | {cell(descriptions.get(m.name, ''))} |")
            lines.append("")
        for m in items:
            if m is head or m.kind in TABLE_KINDS:
                continue
            short = m.name[len(group) + 1 :] if m.name.startswith(group) and m.name != group else m.name
            lines += [f"### {short}", "", f"<Badge type=\"tip\" text=\"{KIND_LABEL.get(m.kind, m.kind)}\" />", ""]
            if m.signatures:
                lines += [f"```{lang}", *m.signatures, "```", ""]
            lines += [md_text(descriptions.get(m.name, "")), ""]
    return "\n".join(lines)


