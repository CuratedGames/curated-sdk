def no_dashes(text: str) -> str:
    """House style: no em or en dashes on the site, even in old release notes."""
    return re.sub(r"\s*[\u2014\u2013]\s*", ": ", text)


def release_notes(body: str) -> str:
    body = no_dashes((body or "").replace("\r\n", "\n"))
    body = body.split("\n## Install", 1)[0]
    body = re.sub(r"^\*\*Curated\.Sdk\*\* [\d.]+\s*$", "", body, flags=re.M).strip()
    body = re.sub(r"^### ", "#### ", body, flags=re.M)
    body = re.sub(r"^## ", "#### ", body, flags=re.M)
    return md_text(body)


def changelog_page(releases: list[dict] | None) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Changelog",
        "",
        f"Release notes from [GitHub Releases]({REPO_URL}/releases), where every package and the "
        "Content Builder binaries are published.",
        "",
    ]
    published = [r for r in (releases or []) if not r.get("draft")]
    if published:
        for r in published:
            date = (r.get("published_at") or "")[:10]
            lines += [f"## {r['tag_name']}", "", f"Released {date}. [Assets and install notes]({r['html_url']})", ""]
            notes = release_notes(r.get("body") or "")
            lines += [notes or "No notes.", ""]
        return "\n".join(lines)
    text = no_dashes((ROOT / "CHANGELOG.md").read_text(encoding="utf-8"))
    text = text.split("## [Unreleased]", 1)[-1]
    text = text.split("\n## ", 1)[1] if "\n## " in text else text
    text = "## " + text
    text = re.sub(r"^## \[([^\]]+)\] - (\S+)", r"## v\1\n\nReleased \2.", text, flags=re.M)
    text = re.sub(r"^### ", "#### ", text, flags=re.M)
    text = re.sub(r"\]\((?!https?://)[^)]*\)", "]", text)
    lines += [
        "::: info",
        "GitHub Releases were not reachable when this page was built, so it shows `CHANGELOG.md`.",
        ":::",
        "",
        md_text(text),
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Game languages (from the fixture every binding is checked against)
# ---------------------------------------------------------------------------


def languages_page() -> str:
    fixture = json.loads((ROOT / "contracts/fixtures/game-language.v1.json").read_text(encoding="utf-8"))
    lines = [
        GENERATED_NOTE,
        "",
        "# Game languages",
        "",
        "Codes returned by `GetCurrentGameLanguage` in every binding, with the Steam client API name "
        "returned by the Steam-name helper. Generated from "
        f"[`contracts/fixtures/game-language.v1.json`]({REPO_URL}/blob/main/contracts/fixtures/game-language.v1.json); "
        "`scripts/check-game-languages.py` fails CI when a binding's table differs from it.",
        "",
        f"Default (outside the launcher, or unknown value): `{fixture['default_language']}`.",
        "",
        "| Code | Language | Steam API name | Also accepted |",
        "| --- | --- | --- | --- |",
    ]
    for lang in fixture["languages"]:
        aliases = ", ".join(f"`{a}`" for a in lang["aliases"])
        lines.append(f"| `{lang['code']}` | {cell(lang['name'])} | `{lang['steam']}` | {aliases} |")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------


def fetch_releases() -> list[dict] | None:
    try:
        return github_json("/releases?per_page=50")
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
        print(f"notice: GitHub Releases unavailable ({e}); using CHANGELOG.md and the csproj version", file=sys.stderr)
        return None


def main() -> int:
    manifest = json.loads((ROOT / "contracts/public-api.v1.json").read_text(encoding="utf-8"))
    releases = None if os.environ.get("DOCS_OFFLINE") else fetch_releases()
    version = resolve_version(releases)
    write(DOCS / ".vitepress/generated.json", json.dumps(version, indent=2) + "\n")
    print(f"version {version['version']} ({version['versionSource']})")

    for binding in public_api.BINDINGS:
        write(DOCS / "reference" / f"{binding}.md", reference_page(binding, manifest))
    write(DOCS / "reference/content-builder.md", cli_reference_page())
    index = [
        GENERATED_NOTE,
        "",
        "# API reference",
        "",
        "Generated on every build from the binding sources and "
        f"[`contracts/public-api.v1.json`]({REPO_URL}/blob/main/contracts/public-api.v1.json).",
        "",
        "| Binding | Members |",
        "| --- | --- |",
    ]
    for binding, info in public_api.BINDINGS.items():
        index.append(f"| [{info['title']}](./{binding}) | {len(manifest['bindings'][binding])} |")
    index += [
        "| [Content Builder CLI](./content-builder) | commands and flags |",
        "| [Game languages](./languages) | language codes and Steam names |",
        "",
    ]
    write(DOCS / "reference/index.md", "\n".join(index))
    write(DOCS / "changelog.md", changelog_page(releases))
    write(DOCS / "reference/languages.md", languages_page())
    print(f"wrote reference pages and changelog ({len(releases or [])} releases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
