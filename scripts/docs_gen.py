#!/usr/bin/env python3
"""Generate the docs.curated.games pages that must never be edited by hand.

Runs before every VitePress build (npm run build in docs/). Writes, all gitignored:

  docs/.vitepress/generated.json   SDK version and tag (latest GitHub Release, else the csproj)
  docs/reference/*.md              API reference from contracts/public-api.v1.json + sources
  docs/reference/content-builder.md  CLI flags parsed from tooling/content-builder/src
  docs/changelog.md                GitHub Releases (falls back to CHANGELOG.md offline)

GITHUB_TOKEN is optional. Without it (or without network) the version comes from
Curated.Sdk/Curated.Sdk.csproj and the changelog from CHANGELOG.md, so local builds work.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import public_api  # noqa: E402

ROOT = public_api.ROOT
DOCS = ROOT / "docs"
REPO = os.environ.get("GITHUB_REPOSITORY", "CuratedGames/curated-sdk")
REPO_URL = f"https://github.com/{REPO}"
GENERATED_NOTE = "<!-- Generated by scripts/docs_gen.py. Do not edit: change the source and rebuild. -->"

LANG = {"dotnet": "csharp", "unity": "csharp", "godot": "gdscript", "unreal": "cpp", "rpgmaker": "js"}
TABLE_KINDS = {"enum-value", "constant", "property", "field", "inspector", "plugin-parameter", "plugin-command", "signal", "event"}
KIND_LABEL = {
    "type": "type",
    "enum": "enum",
    "delegate": "delegate",
    "method": "method",
    "function": "function",
    "constructor": "constructor",
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def md_text(text: str) -> str:
    """Escape text for VitePress markdown (Vue template): raw `<` and `{{` outside code spans."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for part in parts:
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(part)
        else:
            out.append(part.replace("<", "&lt;").replace("{{", "&#123;&#123;"))
    return "".join(out)


def cell(text: str) -> str:
    return md_text(text).replace("|", "\\|").replace("\n", " ")


def github_json(path: str):
    url = f"https://api.github.com/repos/{REPO}{path}"
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "curated-docs-gen"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=20) as res:
        return json.load(res)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


# ---------------------------------------------------------------------------
# Version
# ---------------------------------------------------------------------------


def csproj_version() -> str:
    text = (ROOT / "Curated.Sdk/Curated.Sdk.csproj").read_text(encoding="utf-8")
    return re.search(r"<Version>([^<]+)</Version>", text).group(1).strip()


def resolve_version(releases: list[dict] | None) -> dict:
    if releases:
        latest = next((r for r in releases if not r.get("draft") and not r.get("prerelease")), None)
        if latest:
            tag = latest["tag_name"]
            return {"version": tag.lstrip("v"), "tag": tag, "versionSource": "github-release"}
    version = csproj_version()
    return {"version": version, "tag": f"v{version}", "versionSource": "csproj"}


